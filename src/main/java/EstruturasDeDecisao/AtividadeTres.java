package EstruturasDeDecisao;

public class AtividadeTres {
    static void main() {
        int opcao = 92;
        switch (opcao) {
            case 1:
                System.out.println("Café");
                break;
            case 2:
                System.out.println("Capuccino");
                break;
            case 3:
                System.out.println("Chocolate Quente");
                break;
            case 4:
                System.out.println("Chá");
                break;

            default:
                System.out.println("Opção inválida");
        }
    }
}
